#!/usr/bin/env python3
"""Generate 1-bit bitmap fonts (C++ arrays) for the ParaNav UI from TrueType fonts.

Usage: python3 tools/gen_fonts.py [--font-dir /usr/share/fonts/truetype/dejavu]
Output: lib/navcore/src/ui/fonts_data.cpp
"""
import argparse
import os

from PIL import Image, ImageDraw, ImageFont

PL = "ąćęłńóśźżĄĆĘŁŃÓŚŹŻ"
FULL = "".join(chr(c) for c in range(32, 127)) + PL + "°·–→←↑↓▲▼◄►●✓⚡…Ø›"
DIGITS = " +-.,:/0123456789°–"

AXIS = " +-.,:0123456789m"  # chart axis labels only (altitudes, times): small, few glyphs

# name, ttf file, pixel size, charset
FONTS = [
    ("font_xs", "DejaVuSansCondensed-Bold.ttf", 16, AXIS),
    ("font_s", "DejaVuSansCondensed-Bold.ttf", 22, FULL),
    ("font_sb", "DejaVuSansCondensed-Bold.ttf", 25, FULL),
    ("font_m", "DejaVuSansCondensed-Bold.ttf", 32, FULL),
    ("font_l", "DejaVuSansCondensed-Bold.ttf", 50, FULL),
    ("font_xl", "DejaVuSansCondensed-Bold.ttf", 80, FULL),
    ("font_xxl", "DejaVuSansCondensed-Bold.ttf", 130, DIGITS),
]


def render_glyph(font, ch, threshold=110):
    bbox = font.getbbox(ch, anchor="ls")  # relative to baseline-left
    adv = font.getlength(ch)
    x0, y0, x1, y1 = bbox
    w, h = max(0, x1 - x0), max(0, y1 - y0)
    if w == 0 or h == 0:
        return dict(w=0, h=0, xo=0, yo=0, adv=int(round(adv)), rows=[])
    img = Image.new("L", (w, h), 0)
    d = ImageDraw.Draw(img)
    d.text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
    px = img.load()
    rows = []
    for y in range(h):
        row = bytearray((w + 7) // 8)
        for x in range(w):
            if px[x, y] >= threshold:
                row[x // 8] |= 0x80 >> (x % 8)
        rows.append(bytes(row))
    return dict(w=w, h=h, xo=x0, yo=y0, adv=int(round(adv)), rows=rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font-dir", default="/usr/share/fonts/truetype/dejavu")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "lib", "navcore", "src", "ui", "fonts_data.cpp"))
    a = ap.parse_args()

    out = ['// Generated by tools/gen_fonts.py from DejaVu fonts (Bitstream Vera / DejaVu license). Do not edit.',
           '#include "fonts.h"', "", "namespace ui {", ""]
    total = 0
    for name, ttf, size, chars in FONTS:
        font = ImageFont.truetype(os.path.join(a.font_dir, ttf), size)
        asc, desc = font.getmetrics()
        cps = sorted(set(ord(c) for c in chars))
        bmp = bytearray()
        glyphs = []
        for cp in cps:
            g = render_glyph(font, chr(cp))
            off = len(bmp)
            for r in g["rows"]:
                bmp += r
            glyphs.append((cp, g["w"], g["h"], g["xo"], g["yo"], g["adv"], off))
        total += len(bmp) + len(glyphs) * 12
        out.append(f"static const uint8_t {name}_bmp[{len(bmp)}] = {{")
        for i in range(0, len(bmp), 24):
            out.append("    " + ", ".join(f"0x{b:02X}" for b in bmp[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const Glyph {name}_glyphs[{len(glyphs)}] = {{")
        for cp, w, h, xo, yo, adv, off in glyphs:
            out.append(f"    {{0x{cp:04X}, {w}, {h}, {xo}, {yo}, {adv}, {off}}},")
        out.append("};")
        out.append(f"const Font {name} = {{{name}_bmp, {name}_glyphs, {len(glyphs)}, {asc + desc}, {asc}}};")
        out.append("")
    out.append("}  // namespace ui")
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {a.out}, ~{total // 1024} KiB")


if __name__ == "__main__":
    main()
